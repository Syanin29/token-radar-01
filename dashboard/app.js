  function risksFor(row) {
    var risks = [];
    if (row.age_days === null) risks.push('Age unknown: DefiLlama records no listing date, so maturity uses the 365-day default.');
    else if (row.age_days < 180) risks.push('Young protocol (' + fmtAge(row.age_days) + ' tracked): less history with no token, so the maturity factor is at its low end.');
    if (row.change_7d === null) risks.push('No seven-day growth reported: the growth factor is neutral (1.00x).');
    else if (row.change_7d < -20) risks.push('TVL fell ' + fmtPct(row.change_7d) + ' in seven days: capital is leaving faster than the model discounts.');
    else if (row.change_7d > 50) risks.push('TVL jumped ' + fmtPct(row.change_7d) + ' in seven days: a spike can reverse, and the growth factor is capped.');
    if (row.multiple_source === 'global') risks.push('Thin comps: fewer than ' + DATA.model.min_peers + ' traded peers in ' + (row.category || 'this category') + ', so the multiple is the global median ' + fmtMult(DATA.comps.global_multiple) + ', not a category price.');
    if ((row.chains || []).length > 3) risks.push('TVL spread across ' + row.chains.length + ' chains: farm on the chain where the protocol\'s main activity lives, not everywhere at once.');
    if (!row.watchlist) risks.push('Outside the house watchlist: below the $' + Math.round(DATA.floor_usd / 1e6) + 'M floor or left out by the house rule, so it is an early find, not a confirmed large launch.');
    return risks;
  }

